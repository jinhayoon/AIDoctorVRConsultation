using System;
using System.Collections.Generic;
using System.IO;
using UnityEngine;

public class ConversationLogger : MonoBehaviour
{
    [Header("Storage")]
    [SerializeField] private string rootFolder = "ConversationLogs";
    [SerializeField] private float autoSaveIntervalSeconds = 30f;

    [Serializable]
    public class Turn
    {
        public string role;        // "user" | "assistant"
        public string transcript;
        public string timestamp;   // ISO 8601 UTC
    }

    [Serializable]
    private class Conversation
    {
        public string sessionId;
        public string participantId;
        public string startTime;
        public string endTime;
        public string endReason;
        public List<Turn> turns = new();
        public Dictionary<string, string> metadata = new();
    }

    private Conversation _conversation;
    private string _filePath;
    private float _lastAutoSave;
    private bool _finalized;

    // ?????????????????????????????????????????????????????????????
    // Session lifecycle
    // ?????????????????????????????????????????????????????????????

    public void StartSession(string sessionId, string participantId)
    {
        _conversation = new Conversation
        {
            sessionId = sessionId,
            participantId = participantId,
            startTime = DateTime.UtcNow.ToString("o")
        };

        string dir = Path.Combine(
            Application.persistentDataPath,
            rootFolder,
            string.IsNullOrEmpty(participantId) ? "anonymous" : participantId
        );

        Directory.CreateDirectory(dir);

        _filePath = Path.Combine(
            dir,
            $"{sessionId}_{DateTime.UtcNow:yyyyMMdd_HHmmss}.json"
        );

        _finalized = false;
        Debug.Log($"[ConversationLogger] Started ? {_filePath}");
    }

    public void AddMetadata(string key, string value)
    {
        if (_conversation != null)
            _conversation.metadata[key] = value;
    }

    // ?????????????????????????????????????????????????????????????
    // Logging API (FINAL transcripts only)
    // ?????????????????????????????????????????????????????????????

    public void LogUser(string transcript)
    {
        if (_conversation == null || string.IsNullOrWhiteSpace(transcript)) return;

        _conversation.turns.Add(new Turn
        {
            role = "user",
            transcript = transcript,
            timestamp = DateTime.UtcNow.ToString("o")
        });
    }

    public void LogAssistant(string transcript)
    {
        if (_conversation == null || string.IsNullOrWhiteSpace(transcript)) return;

        _conversation.turns.Add(new Turn
        {
            role = "AIDoc",
            transcript = transcript,
            timestamp = DateTime.UtcNow.ToString("o")
        });
    }

    // ?????????????????????????????????????????????????????????????
    // Saving
    // ?????????????????????????????????????????????????????????????

    public void FinalizeAndSave(string reason)
    {
        if (_conversation == null || _finalized) return;

        _conversation.endTime = DateTime.UtcNow.ToString("o");
        _conversation.endReason = reason;

        WriteToDisk();
        _finalized = true;

        Debug.Log($"[ConversationLogger] Finalized ({reason})");
    }

    private void WriteToDisk()
    {
        try
        {
            string json = JsonUtility.ToJson(_conversation, true);
            File.WriteAllText(_filePath, json);
        }
        catch (Exception e)
        {
            Debug.LogError($"[ConversationLogger] Save failed: {e.Message}");
        }
    }

    // ?????????????????????????????????????????????????????????????
    // Resilience
    // ?????????????????????????????????????????????????????????????

    private void Update()
    {
        if (_conversation == null || _finalized) return;

        if (autoSaveIntervalSeconds > 0 &&
            Time.time - _lastAutoSave > autoSaveIntervalSeconds)
        {
            _lastAutoSave = Time.time;
            WriteToDisk();
        }
    }

    private void OnDestroy() => FinalizeAndSave("scene_destroyed");
    private void OnApplicationQuit() => FinalizeAndSave("application_quit");
    private void OnApplicationPause(bool pause)
    {
        if (pause) FinalizeAndSave("application_paused");
    }
}